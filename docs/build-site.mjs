// ── algorithms ───────────────────────────────────────────────────────────────

function algorithms(locale) {
  const t = T[locale]
  const html = readFileSync(path.join(DOCS, 'src', `guide.${locale}.html`), 'utf8')
  const guide = parseGuide(html)
  const outline = parseOutline(html)
  const parts = parseParts(html)
  const partByTitle = Object.fromEntries(parts.map(p => [p.title, p]))

  // table of contents, grouped by the guide's own parts
  let toc = '', seenPart = null
  for (const { className, part } of outline) {
    const e = guide[className]
    if (!e) continue
    if (part !== seenPart) { toc += `\n  <div class="grp">${raw(part)}</div>`; seenPart = part }
    toc += `\n  <a href="#${slug(className)}">${raw(e.title)}</a>`
  }

  let body = ''
  seenPart = null
  for (const { className, part } of outline) {
    const e = guide[className]
    if (!e) continue
    if (part !== seenPart) {
      const p = partByTitle[part]
      body += `\n<div class="part-head">
  <div class="lbl">${raw(p?.label ?? '')}</div>
  <h2>${raw(part)}</h2>
  ${p?.lede ? `<p>${raw(p.lede)}</p>` : ''}
</div>`
      seenPart = part
    }
    const tags = e.tags.map(tg =>
      `<span class="tg tg-${tg.kind.replace('tag-', '')}">${raw(tg.label)}</span>`).join('')
    body += `
<article class="algo-card" id="${slug(className)}">
  <header>
    <div class="hd"><span class="num">${raw(e.number)}</span><h3>${raw(e.title)}</h3></div>
    <div class="meta"><span class="cls">${esc(e.className)}</span>${tags}</div>
  </header>
  <div class="gd">${e.body}</div>
</article>`
  }

  return `${head(locale, 'algos', `${t.algosTitle} — ${t.title}`, t.algosLede)}
${topbar(locale, 'algos', t)}

<div class="algos-head"><div class="wrap">
  <h1>${esc(t.algosTitle)}</h1>
  <p>${esc(t.algosLede)}</p>
</div></div>

<div class="wrap"><div class="algos-layout">
  <aside class="toc">
    <div class="t">${esc(t.onThisPage)}</div>${toc}
  </aside>
  <main>${body}
  </main>
</div></div>

${footer(locale, t)}`
}

// ── run ──────────────────────────────────────────────────────────────────────

// The installers live at the repository root — that is the copy the launcher re-runs for
// `dlpx-helper update`. They are copied here so the one-liner on the site can fetch them from
// the Pages URL, which only serves docs/.
for (const script of ['install.sh', 'install.ps1']) {
  copyFileSync(path.join(DOCS, '..', script), path.join(DOCS, script))
  console.log(`  copied ${script}`)
}

let n = 0
for (const locale of LOCALES) {
  writeFileSync(path.join(DOCS, PAGES[locale].home), landing(locale)); n++
  writeFileSync(path.join(DOCS, PAGES[locale].algos), algorithms(locale)); n++
  console.log(`  ${locale}: ${PAGES[locale].home}, ${PAGES[locale].algos}`)
}
console.log(`${n} pages written to docs/`)
