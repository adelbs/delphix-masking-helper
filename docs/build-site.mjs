/**
 * Generates the GitHub Pages site into docs/ — the folder GitHub serves when Pages is set to
 * "deploy from branch, /docs".
 *
 *   docs/index.html            landing (English, the site root)
 *   docs/index.pt-BR.html      landing (Portuguese)
 *   docs/index.es.html         landing (Spanish)
 *   docs/algorithms*.html      the algorithm reference, one page per language
 *
 * The algorithm content is read from docs/src/guide.<locale>.html — the same source the PDFs
 * are built from and the same one the app's Documentation tab uses — so the site cannot drift
 * from either. Copy lives in docs/site-content.mjs.
 *
 *   node docs/build-site.mjs
 */

import { readFileSync, writeFileSync, statSync, copyFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { LOCALES, parseGuide, parseParts, parseOutline } from './guide-parser.mjs'
import { T, PAGES, LANG_NAMES, LANG_ABBR, REPO, SITE } from './site-content.mjs'

const DOCS = path.dirname(fileURLToPath(import.meta.url))
const pdfName = (l) => `delphix-algorithms-guide.${l}.pdf`

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
/** Guide headings are already HTML-escaped in the source; do not double-escape them. */
const raw = (s) => String(s)
const slug = (className) => className.split('.').pop().replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

const MARK = '<!-- Generated by docs/build-site.mjs from docs/src/guide.<locale>.html — do not edit by hand. -->'

const LOGO = `<svg viewBox="0 0 48 46" fill="none" aria-hidden="true"><path fill="#1189bd" d="M25.946 44.938c-.664.845-2.021.375-2.021-.698V33.937a2.26 2.26 0 0 0-2.262-2.262H10.287c-.92 0-1.456-1.04-.92-1.788l7.48-10.471c1.07-1.497 0-3.578-1.842-3.578H1.237c-.92 0-1.456-1.04-.92-1.788L10.2.53A1.13 1.13 0 0 1 11.12 0h25.494c.92 0 1.456 1.04.92 1.788l-7.48 10.471c-1.07 1.498 0 3.578 1.842 3.578h14.767c.92 0 1.456 1.04.92 1.788z"/></svg>`

function head(locale, page, title, desc) {
  const other = LOCALES.filter(l => l !== locale)
  const alt = other.map(l =>
    `<link rel="alternate" hreflang="${l}" href="${PAGES[l][page]}">`).join('\n  ')
  return `<!doctype html>
<html lang="${PAGES[locale].htmlLang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:type" content="website">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="site.css">
${alt}
</head>
<body>
${MARK}`
}

function topbar(locale, page, t) {
  // Both spellings ship; CSS shows the code instead of the name when the bar gets tight,
  // so every language stays reachable at any width instead of being hidden behind a menu.
  const langs = LOCALES.map(l =>
    `<a href="${PAGES[l][page]}"${l === locale ? ' aria-current="true"' : ''} hreflang="${l}"`
    + ` title="${esc(LANG_NAMES[l])}">`
    + `<span class="full">${esc(LANG_NAMES[l])}</span>`
    + `<span class="abbr">${LANG_ABBR[l]}</span></a>`
  ).join('')
  return `<header class="topbar"><div class="wrap">
  <a class="brand" href="${PAGES[locale].home}">${LOGO}<span>${esc(t.title)}</span></a>
  <nav>
    <a href="${PAGES[locale].algos}">${esc(t.algosTitle)}</a>
    <a href="${REPO}">GitHub</a>
    <span class="langs">${langs}</span>
  </nav>
</div></header>`
}

/** Copy buttons for the install commands. Inline and tiny — the site ships no JavaScript
 *  otherwise, and a command you must retype by hand is a command you get wrong. */
const COPY_SCRIPT = `<script>
(function () {
  // Two ways to copy, because the modern one is not always available: it needs a secure
  // context and the user's permission, and it rejects silently when denied. Falling back to
  // the old execCommand, and finally to selecting the text, means the button always does
  // something the visitor can act on.
  function copy(text, el) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text);
    }
    return new Promise(function (resolve, reject) {
      var ta = document.createElement('textarea');
      ta.value = text;
      ta.setAttribute('readonly', '');
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      var okay = false;
      try { okay = document.execCommand('copy'); } catch (e) { okay = false; }
      document.body.removeChild(ta);
      okay ? resolve() : reject();
    });
  }

  function selectText(el) {
    var r = document.createRange();
    r.selectNodeContents(el);
    var sel = window.getSelection();
    sel.removeAllRanges();
    sel.addRange(r);
  }

  document.querySelectorAll('.copy').forEach(function (b) {
    b.addEventListener('click', function () {
      var code = b.closest('.cmd').querySelector('code');
      var was = b.textContent;
      copy(code.textContent, code).then(function () {
        b.textContent = b.dataset.copied;
        b.classList.add('done');
        setTimeout(function () { b.textContent = was; b.classList.remove('done'); }, 1600);
      }).catch(function () {
        // Nothing could be written: leave the command selected so it can be copied by hand.
        selectText(code);
      });
    });
  });
})();
</script>`

function footer(locale, t) {
  return `<footer><div class="wrap">
  <div class="rows">
    <a href="${REPO}">${esc(t.footerRepo)}</a>
  </div>
  <p class="lic">${esc(t.footerLicense)}</p>
</div></footer>
${COPY_SCRIPT}
</body>
</html>`
}

function pdfLinks(t) {
  return LOCALES.map(l => {
    const size = (statSync(path.join(DOCS, pdfName(l))).size / 1024 / 1024).toFixed(1)
    return `<a href="${pdfName(l)}" download>${esc(LANG_NAMES[l])} <span class="sz">PDF · ${size} MB</span></a>`
  }).join('\n    ')
}

